// Regenerates supabase/seed_sample_spots.sql from public/js/samples.js.
// Usage: node scripts/make-seed.mjs
import { writeFileSync } from 'node:fs';
import { SAMPLE_SPOTS } from '../public/js/samples.js';

const q = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === undefined || v === null ? 'null' : String(v));
const arr = (a, type) => `array[${a.map(type === 'text' ? q : n).join(',')}]::${type}[]`;

const rows = SAMPLE_SPOTS.map((s) => {
  const events = s.eventDates === 'saturdays'
    ? "array[v_sat, v_sat + 14, v_sat + 28]"
    : "'{}'::date[]";
  return `
  insert into public.spots (owner_id, title, description, city, area, distance_mi, spot_type, covered, spot_count,
    rent_options, price_day_cents, price_week_cents, price_month_cents, price_event_cents, avail_days,
    start_time, end_time, event_label, event_dates, photos, rating, review_count, is_sample)
  values (v_owner, ${q(s.title)}, ${q(s.description)}, ${q(s.city)}, ${q(s.area)}, ${n(s.distance_mi)}, ${q(s.spot_type)}, ${s.covered}, ${s.spot_count},
    ${arr(s.rent_options, 'text')}, ${n(s.price_day_cents)}, ${n(s.price_week_cents)}, ${n(s.price_month_cents)}, ${n(s.price_event_cents)}, ${arr(s.avail_days, 'smallint')},
    ${q(s.start_time)}, ${q(s.end_time)}, ${q(s.event_label || '')}, ${events}, ${arr(s.photos, 'text')}, ${n(s.rating)}, ${s.review_count}, true)
  returning id into v_spot;
  insert into public.spot_addresses (spot_id, street_address) values (v_spot, ${q(s.address)});`;
}).join('\n');

const sql = `-- Placeholder parking spots, owned by your team's Spotted account.
-- 1. Sign up on the live site with the team account.
-- 2. Replace the email below, then run this whole file in Supabase > SQL Editor.
-- Running it again replaces the previous sample spots.
-- Generated by scripts/make-seed.mjs; edit public/js/samples.js instead.

do $$
declare
  v_email text := 'spottedparking@outlook.com';
  v_owner uuid;
  v_spot uuid;
  v_today date := (now() at time zone 'America/Denver')::date;
  v_sat date := v_today + ((6 - extract(dow from v_today)::int + 7) % 7);
begin
  if v_sat = v_today then v_sat := v_sat + 7; end if;
  select id into v_owner from auth.users where lower(email) = lower(v_email);
  if v_owner is null then
    raise exception 'No Spotted account uses %. Sign up on the site first.', v_email;
  end if;
  delete from public.spots where is_sample and owner_id = v_owner;
${rows}
end $$;
`;

writeFileSync(new URL('../supabase/seed_sample_spots.sql', import.meta.url), sql);
console.log('wrote supabase/seed_sample_spots.sql');
